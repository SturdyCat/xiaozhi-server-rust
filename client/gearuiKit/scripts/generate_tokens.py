#!/usr/bin/env python3
"""Generate com/gearui/theme/TypographyProfiles.kt from tokens/typography.tokens.json.

The generated file holds a single "canonical ramp" built with TextStyle.fromRem(...),
so the rem typography system (16sp == 1rem, line-height in sp) is the one source of truth.
Run from anywhere: `python3 gearuiKit/scripts/generate_tokens.py`
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TOKENS = os.path.normpath(os.path.join(HERE, "..", "tokens", "typography.tokens.json"))
OUT = os.path.normpath(
    os.path.join(
        HERE, "..", "src", "commonMain", "kotlin", "com", "gearui", "theme", "TypographyProfiles.kt"
    )
)


def main() -> None:
    with open(TOKENS, "r", encoding="utf-8") as fh:
        data = json.load(fh)

    ratios = {str(k): v for k, v in data["ratiosByRem"].items()}
    tokens = data["tokens"]

    lines = [
        "// Generated by scripts/generate_tokens.py. Edit tokens/typography.tokens.json.",
        "package com.gearui.theme",
        "",
        "import com.gearui.foundation.typography.TextStyle",
        "import com.tencent.kuikly.compose.ui.text.font.FontWeight",
        "",
        "internal object TypographyProfiles {",
        "    val Reference = Typography(",
    ]

    for name, spec in tokens.items():
        rem = spec["rem"]
        weight = spec["weight"]
        ratio = ratios[str(rem)]
        lines.append(
            f"        {name} = TextStyle.fromRem({rem}, {ratio}, FontWeight({weight})),"
        )

    lines += [
        "    )",
        "}",
        "",
    ]

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("Wrote", os.path.abspath(OUT))


if __name__ == "__main__":
    main()
