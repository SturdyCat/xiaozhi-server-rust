#!/usr/bin/env bash
# 生成 client/apps/h5App/em/static/dashboard.js —— 官方 EchoMuse dashboard.jsx 的编译产物。
#
# 为什么脚本化而不是手改：
#   1. dashboard.jsx 是**逐字拷贝**的上游源码（源真相），任何手改都会让下次升版对不上；
#   2. dashboard.jsx 的最后一行是 `ReactDOM.createRoot(...).render(<App/>)`，加载即自动
#      挂载官方 App（它会去请求 /api/auth/me、/api/events、Settings、配网向导）。本移植只
#      要 Card + Detail，所以生成物里必须摘掉这一行，改由 static/host.js 挂载。这里断言
#      替换次数 == 1，上游改了写法会立刻失败而不是静默双挂载；
#   3. 产物入库并在首行写入 src-sha256 横幅，Gradle 的 verifyEmBundle 用它确认
#      "dashboard.js 确实由当前 dashboard.jsx 编译而来"。改了 jsx 忘了重跑本脚本 →
#      :apps:h5App:publishWeb 直接失败。
#
# 用法：tools/build_em_dashboard.sh
#   ESBUILD_BIN=/path/to/esbuild tools/build_em_dashboard.sh   # 指定本地 esbuild
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="$ROOT/client/apps/h5App/em/static"
SRC="$DIR/dashboard.jsx"
OUT="$DIR/dashboard.js"
# 与上游 controller/Dockerfile 同一版本，保证 --jsx=transform 的产物形态一致。
ESBUILD_VERSION="${ESBUILD_VERSION:-0.20.2}"

[ -f "$SRC" ] || { echo "缺少 $SRC" >&2; exit 1; }

SRC_SHA="$(shasum -a 256 "$SRC" | cut -d' ' -f1)"
BANNER="/* em-bundle src-sha256=${SRC_SHA} esbuild=${ESBUILD_VERSION} — GENERATED by tools/build_em_dashboard.sh, DO NOT EDIT */"

ESBUILD="${ESBUILD_BIN:-}"
if [ -z "$ESBUILD" ]; then
  if command -v esbuild >/dev/null 2>&1; then
    ESBUILD="esbuild"
  else
    ESBUILD="npx --yes esbuild@${ESBUILD_VERSION}"
  fi
fi

# --bundle=false：与上游完全一致，React/ReactDOM/xterm 走全局 UMD，产物是经典脚本
# （顶层 function 声明成为 window 属性，const 留在全局词法环境）。
$ESBUILD "$SRC" \
  --bundle=false \
  --jsx=transform \
  --jsx-factory=React.createElement \
  --jsx-fragment=React.Fragment \
  --target=es2019 \
  --charset=utf8 \
  "--banner:js=${BANNER}" \
  --outfile="$OUT"

# 摘除官方 App 自动挂载（保留 Card/Detail 等全部组件定义）。
python3 - "$OUT" <<'PY'
import re, sys
path = sys.argv[1]
text = open(path, encoding='utf-8').read()
pattern = re.compile(
    r'ReactDOM\.createRoot\(document\.getElementById\("root"\)\)\.render\('
    r'(?:/\* @__PURE__ \*/ )?React\.createElement\(App, null\)\);'
)
text, count = pattern.subn(
    '/* em-host: App auto-mount removed (host.js mounts Card + Detail) */', text)
if count != 1:
    sys.exit('期望摘除 1 处 App 自动挂载，实际 %d 处：上游已改动，请检查 dashboard.jsx 尾部' % count)
open(path, 'w', encoding='utf-8').write(text)
print('摘除 App 自动挂载: 1 处')
PY

DEST_SHA="$(shasum -a 256 "$OUT" | cut -d' ' -f1)"
{
  echo "src  dashboard.jsx  $SRC_SHA"
  echo "out  dashboard.js   $DEST_SHA"
} > "$ROOT/client/apps/h5App/em/README.sha256"

echo "已生成 $OUT"
cat "$ROOT/client/apps/h5App/em/README.sha256"
